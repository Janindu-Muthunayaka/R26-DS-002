def check_audio_quality(filepath):
    """
    Loads an audio file and checks basic quality:
    - Sample rate
    - Duration
    - Peak amplitude (is it too quiet?)
    - Silence detection
    """
    try:
        audio, sr = librosa.load(filepath, sr=None)
        duration = librosa.get_duration(y=audio, sr=sr)
        peak_amplitude = np.max(np.abs(audio))
        rms = np.sqrt(np.mean(audio**2))

        # Silence detection — if RMS is very low, audio may be empty
        is_silent = rms < 0.01

        status = '⚠️  May be too quiet' if is_silent else '✅ Audio OK'

        return {
            'file': os.path.basename(filepath),
            'sample_rate': sr,
            'duration_sec': round(duration, 2),
            'peak_amplitude': round(float(peak_amplitude), 4),
            'rms_energy': round(float(rms), 4),
            'status': status
        }
    except Exception as e:
        return {'file': filepath, 'error': str(e)}


