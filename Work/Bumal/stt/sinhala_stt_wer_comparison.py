"""## 🤖 Step 7 — Load and Run All Three Whisper Models

This is the main evaluation step. We will:
1. Load each model (base → small → medium)
2. Transcribe all audio files with each model
3. Record transcription time
4. Calculate WER and CER for each

> **Note:** First run downloads model weights from internet. base ~140MB, small ~460MB, medium ~1.5GB. This is a one-time download per session.
"""

def transcribe_with_model(model_name, audio_files, ground_truth, device):

    print(f'\n' + '='*60)
    print(f'  MODEL: whisper-{model_name.upper()}')
    print('='*60)

    load_start = time.time()
    print(f'  Loading whisper-{model_name}...')
    model = whisper.load_model(model_name, device=device)
    load_time = time.time() - load_start
    print(f'  ✅ Model loaded in {load_time:.1f}s')

    results = []

    for audio_file in audio_files:

        # Match converted filename back to original for ground truth lookup
        original_name = audio_file.replace('converted_', '')
        if original_name not in ground_truth:
            print(f'  ⚠️  Skipping {audio_file} — no ground truth')
            continue

        ref_text = ground_truth[original_name]
        print(f'\n  ─── {original_name} ───')
        print(f'  Reference : "{ref_text}"')

        # Load audio directly as numpy array — avoids librosa warning
        audio = whisper.load_audio(audio_file)
        audio = whisper.pad_or_trim(audio)

        # Create mel spectrogram — Whisper's actual input format
        mel = whisper.log_mel_spectrogram(audio).to(device)

        # Transcribe
        t_start = time.time()
        result = model.transcribe(
            audio_file,
            language='si',
            task='transcribe',
            temperature=0.0,
            beam_size=5,
            best_of=5,
            fp16=(device == 'cuda'),
            no_speech_threshold=0.3,
            logprob_threshold=-0.5,
            compression_ratio_threshold=1.35,
            condition_on_previous_text=False,
        )
        transcription_time = time.time() - t_start

        hypothesis = result['text'].strip()
        detected_lang = result.get('language', 'unknown')

        # Hallucination detection
        words = hypothesis.split()
        is_hallucination = False

        if len(words) > 5:
            unique_words = set(words)
            if len(unique_words) <= 2:
                is_hallucination = True

        if len(hypothesis) > 10:
            chars = list(hypothesis.replace(' ', ''))
            unique_chars = set(chars)
            if len(unique_chars) <= 2:
                is_hallucination = True

        if is_hallucination:
            print(f'  ⚠️  Hallucination detected!')
            hypothesis = '[HALLUCINATION — model failed on this sample]'
            word_error_rate = 1.0
            char_error_rate = 1.0
        else:
            word_error_rate = wer(ref_text, hypothesis)
            char_error_rate = cer(ref_text, hypothesis)

        print(f'  Whisper output : "{hypothesis}"')
        print(f'  WER  : {word_error_rate*100:.2f}%')
        print(f'  CER  : {char_error_rate*100:.2f}%')
        print(f'  Time : {transcription_time:.2f}s')
        print(f'  Lang : {detected_lang}')

        results.append({
            'model'                 : f'whisper-{model_name}',
            'audio_file'            : original_name,
            'reference'             : ref_text,
            'whisper_transcription' : hypothesis,
            'wer'                   : round(word_error_rate, 4),
            'wer_percent'           : round(word_error_rate * 100, 2),
            'cer'                   : round(char_error_rate, 4),
            'cer_percent'           : round(char_error_rate * 100, 2),
            'transcription_time_sec': round(transcription_time, 2),
            'detected_language'     : detected_lang,
            'hallucination'         : is_hallucination
        })

    del model
    if device == 'cuda':
        torch.cuda.empty_cache()

    return results


