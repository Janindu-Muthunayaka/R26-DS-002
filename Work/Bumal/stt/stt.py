import torch
import librosa
import soundfile as sf
from transformers import AutoProcessor, Wav2Vec2BertForCTC

model_name = "L-Inuri/Wav2Vec-BERT"

print("Loading processor...")
processor = AutoProcessor.from_pretrained(model_name)

print("Loading model...")
model = Wav2Vec2BertForCTC.from_pretrained(model_name)

model.eval()
print("✅ Model loaded successfully!")

from google.colab import files

print("Upload your Sinhala audio file (.wav or .mp3)")
uploaded = files.upload()

# Get the uploaded filename
audio_filename = list(uploaded.keys())[0]
print(f"✅ Uploaded file: {audio_filename}")

import librosa

# Store all processed audio arrays
audio_data = {}

for filename in uploaded.keys():
    print(f"Loading: {filename}")

    # Load and resample each file to 16kHz
    audio_array, sampling_rate = librosa.load(filename, sr=16000, mono=True)

    audio_data[filename] = audio_array

    print(f"   ✅ Loaded successfully!")
    print(f"   Sample rate : {sampling_rate} Hz")
    print(f"   Duration    : {len(audio_array)/sampling_rate:.2f} seconds")
    print("-" * 40)

print(f"\n✅ Total files loaded: {len(audio_data)}")

# Run Speech to Text on all loaded files
print("=" * 50)
print("📝 Transcription Results:")
print("=" * 50)

all_transcriptions = {}

for filename, audio_array in audio_data.items():

    # Process the audio
    inputs = processor(
        audio_array,
        sampling_rate=16000,
        return_tensors="pt",
        padding=True
    )

    # Run inference
    with torch.no_grad():
        logits = model(**inputs).logits

    # Decode the output
    predicted_ids = torch.argmax(logits, dim=-1)
    transcription = processor.batch_decode(predicted_ids)

    all_transcriptions[filename] = transcription[0]

    print(f"File : {filename}")
    print(f"Text : {transcription[0]}")
    print("-" * 40)

