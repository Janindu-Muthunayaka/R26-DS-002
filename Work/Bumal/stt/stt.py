whisper_transcriptions = {}

for filename, audio_array in audio_data.items():

    # Process audio
    inputs = whisper_processor(
        audio_array,
        sampling_rate=16000,
        return_tensors="pt"
    )

    # Generate transcription — language forced via generate kwargs
    with torch.no_grad():
        predicted_ids = whisper_model.generate(
            inputs["input_features"],
            language="si",
            task="transcribe"
        )

    # Decode output
    whisper_text = whisper_processor.batch_decode(
        predicted_ids,
        skip_special_tokens=True
    )[0].strip()

    whisper_transcriptions[filename] = whisper_text

    print(f"File : {filename}")
    print(f"Text : {whisper_text}")
    print("-" * 40)

